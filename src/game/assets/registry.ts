let cached: readonly AssetRecord[] | null = null;

export function assetRegistry(): readonly AssetRecord[] {
  if (!cached) cached = [...CORE, ...landmarks()];
  return cached;
}

export function assetById(id: string): AssetRecord | null {
  return assetRegistry().find((item) => item.id === id) ?? null;
}

