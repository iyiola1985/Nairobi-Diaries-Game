const absent = (
  partial: Pick<AssetRecord, 'id' | 'role' | 'title' | 'notes'> & Partial<Pick<AssetRecord, 'slots' | 'rigId' | 'placement'>>,
): AssetRecord => ({
  status: 'absent',
  file: null,
  format: 'glb',
  license: 'Not supplied. Do not substitute a scraped or unlicensed model.',
  provenance: 'No file in this repository.',
  lod: null,
  rigId: partial.rigId ?? null,
  slots: partial.slots ?? [],
  placement: partial.placement ?? null,
  ...partial,
});

function centroid(polygon: [number, number][]): [number, number] {
  let x = 0;
  let z = 0;
  for (const point of polygon) {
    x += point[0];
    z += point[1];
  }
  return [x / polygon.length, z / polygon.length];
}

function place(x: number, z: number, heightM: number | null): AssetPlacement {
  const geo = unproject(x, z);
  return { x, z, lat: geo.lat, lon: geo.lon, heightM };
}

function landmarks(): AssetRecord[] {
  const records: AssetRecord[] = [];
  for (const building of cbd.buildings) {
    if (building.special === 'kicc' && building.accent) {
      records.push(
        absent({
          id: 'landmark-kicc',
          role: 'landmark',
          title: 'KICC tower',
          placement: place(building.accent.cx, building.accent.cz, 105),
          notes:
            'Drop a commissioned GLB here later. The live scene uses a cylinder at this OSM position. That cylinder is not this asset.',
        }),
      );
    }
    if (building.special === 'times-tower') {
      const [x, z] = centroid(building.polygon);
      records.push(
        absent({
          id: 'landmark-times-tower',
          role: 'landmark',
          title: 'Times Tower',
          placement: place(x, z, 140),
          notes:
            'Drop a commissioned GLB here later. The live scene extrudes the OSM footprint. That extrusion is not this asset.',
        }),
      );
    }
  }
  return records;
}

