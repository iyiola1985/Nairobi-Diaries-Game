/**
 * Writes an original 1 metre cube as a glTF binary.
 * This is a loader probe, not a character, building, or landmark.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const faces = [
  { n: [0, 1, 0], v: [[-0.5, 1, -0.5], [0.5, 1, -0.5], [0.5, 1, 0.5], [-0.5, 1, 0.5]] },
  { n: [0, -1, 0], v: [[-0.5, 0, 0.5], [0.5, 0, 0.5], [0.5, 0, -0.5], [-0.5, 0, -0.5]] },
  { n: [0, 0, 1], v: [[-0.5, 0, 0.5], [0.5, 0, 0.5], [0.5, 1, 0.5], [-0.5, 1, 0.5]] },
  { n: [0, 0, -1], v: [[0.5, 0, -0.5], [-0.5, 0, -0.5], [-0.5, 1, -0.5], [0.5, 1, -0.5]] },
  { n: [1, 0, 0], v: [[0.5, 0, 0.5], [0.5, 0, -0.5], [0.5, 1, -0.5], [0.5, 1, 0.5]] },
  { n: [-1, 0, 0], v: [[-0.5, 0, -0.5], [-0.5, 0, 0.5], [-0.5, 1, 0.5], [-0.5, 1, -0.5]] },
];

const positions = [];
const normals = [];
const indices = [];
for (const face of faces) {
  const start = positions.length / 3;
  for (const vertex of face.v) {
    positions.push(vertex[0], vertex[1], vertex[2]);
    normals.push(face.n[0], face.n[1], face.n[2]);
  }
  indices.push(start, start + 1, start + 2, start, start + 2, start + 3);
}

const positionBytes = Buffer.from(new Float32Array(positions).buffer);
const normalBytes = Buffer.from(new Float32Array(normals).buffer);
const indexBytes = Buffer.from(new Uint16Array(indices).buffer);
const bin = Buffer.concat([positionBytes, normalBytes, indexBytes]);

const json = {
  asset: {
    version: '2.0',
    generator: 'nairobidiaries-write-probe-glb',
    copyright: 'Original NairobiDiaries pipeline probe. Not a third-party model.',
  },
  scene: 0,
  scenes: [{ name: 'Probe', nodes: [0] }],
  nodes: [{ name: 'PipelineProbe', mesh: 0 }],
  meshes: [
    {
      name: 'PipelineProbe',
      primitives: [
        {
          attributes: { POSITION: 0, NORMAL: 1 },
          indices: 2,
          material: 0,
        },
      ],
    },
  ],
  materials: [
    {
      name: 'probe-brass',
      pbrMetallicRoughness: {
        baseColorFactor: [0.84, 0.69, 0.48, 1],
        metallicFactor: 0.08,
        roughnessFactor: 0.42,
      },
    },
  ],
  accessors: [
    {
      bufferView: 0,
      componentType: 5126,
      count: positions.length / 3,
      type: 'VEC3',
      min: [-0.5, 0, -0.5],
      max: [0.5, 1, 0.5],
    },
    {
      bufferView: 1,
      componentType: 5126,
      count: normals.length / 3,
      type: 'VEC3',
    },
    {
      bufferView: 2,
      componentType: 5123,
      count: indices.length,
      type: 'SCALAR',
    },
  ],
  bufferViews: [
    { buffer: 0, byteOffset: 0, byteLength: positionBytes.length, target: 34962 },
    { buffer: 0, byteOffset: positionBytes.length, byteLength: normalBytes.length, target: 34962 },
    {
      buffer: 0,
      byteOffset: positionBytes.length + normalBytes.length,
      byteLength: indexBytes.length,
      target: 34963,
    },
  ],
  buffers: [{ byteLength: bin.length }],
};

let jsonText = JSON.stringify(json);
while (jsonText.length % 4 !== 0) jsonText += ' ';
const jsonBytes = Buffer.from(jsonText, 'utf8');

const header = 12;
const jsonChunk = 8 + jsonBytes.length;
const binChunk = 8 + bin.length;
const total = header + jsonChunk + binChunk;
const file = Buffer.alloc(total);
let cursor = 0;
file.writeUInt32LE(0x46546c67, cursor);
cursor += 4;
file.writeUInt32LE(2, cursor);
cursor += 4;
file.writeUInt32LE(total, cursor);
cursor += 4;
file.writeUInt32LE(jsonBytes.length, cursor);
cursor += 4;
file.writeUInt32LE(0x4e4f534a, cursor);
cursor += 4;
jsonBytes.copy(file, cursor);
cursor += jsonBytes.length;
file.writeUInt32LE(bin.length, cursor);
cursor += 4;
file.writeUInt32LE(0x004e4942, cursor);
cursor += 4;
bin.copy(file, cursor);

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'public/assets/probes/pipeline-probe.glb');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, file);
const fixture = resolve(root, 'src/game/assets/probe.glb.ts');
const source = `/** Generated by scripts/write-probe-glb.mjs. Original 1 metre probe. Not a character or landmark. */\nexport const PROBE_GLB_BASE64 = '${file.toString('base64')}';\n`;
writeFileSync(fixture, source);
console.log(`wrote ${out} (${file.length} bytes, ${indices.length / 3} triangles)`);
